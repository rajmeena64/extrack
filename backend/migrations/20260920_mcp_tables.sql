CREATE TABLE IF NOT EXISTS app_auth.user_mcp_connections (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES app_auth.users(id) ON DELETE CASCADE,
  client_name TEXT NOT NULL DEFAULT 'AI Client',
  token_hash TEXT NOT NULL UNIQUE,
  refresh_token_hash TEXT UNIQUE,
  is_active BOOLEAN NOT NULL DEFAULT true,
  disabled_tools JSONB NOT NULL DEFAULT '[]'::jsonb,
  last_used_at TIMESTAMPTZ,
  expires_at TIMESTAMPTZ NOT NULL,
  refresh_expires_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS user_mcp_connections_user_id_idx ON app_auth.user_mcp_connections(user_id);
CREATE INDEX IF NOT EXISTS user_mcp_connections_token_hash_idx ON app_auth.user_mcp_connections(token_hash) WHERE is_active = true;
CREATE INDEX IF NOT EXISTS user_mcp_connections_refresh_token_hash_idx ON app_auth.user_mcp_connections(refresh_token_hash) WHERE is_active = true;

