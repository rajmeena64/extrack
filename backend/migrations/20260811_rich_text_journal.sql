CREATE TABLE IF NOT EXISTS trading.journal_entries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES app_auth.users(id) ON DELETE CASCADE,
  trade_id BIGINT REFERENCES trading.trades(id) ON DELETE CASCADE,
  journal_date DATE,
  content JSONB NOT NULL DEFAULT '{"type":"doc","content":[{"type":"paragraph"}]}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT journal_entry_target_check CHECK ((trade_id IS NOT NULL) <> (journal_date IS NOT NULL)),
  CONSTRAINT journal_entry_content_size_check CHECK (octet_length(content::text) <= 102400)
);

CREATE UNIQUE INDEX IF NOT EXISTS journal_entries_user_trade_unique
  ON trading.journal_entries(user_id, trade_id) WHERE trade_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS journal_entries_user_date_unique
  ON trading.journal_entries(user_id, journal_date) WHERE journal_date IS NOT NULL;

