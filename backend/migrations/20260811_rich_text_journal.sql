SELECT user_id, id, jsonb_build_object(
  'type', 'doc',
  'content', jsonb_build_array(jsonb_build_object(
    'type', 'paragraph',
    'content', jsonb_build_array(jsonb_build_object('type', 'text', 'text', notes))
  ))
)
FROM trading.trades
WHERE NULLIF(BTRIM(notes), '') IS NOT NULL
ON CONFLICT (user_id, trade_id) WHERE trade_id IS NOT NULL DO NOTHING;
