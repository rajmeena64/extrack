CREATE TABLE IF NOT EXISTS trading.trades (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  legacy_id BIGINT,
  user_id INTEGER NOT NULL REFERENCES app_auth.users(id) ON DELETE CASCADE,
  account_id BIGINT,
  broker_id TEXT,
  exchange_id TEXT,
  source TEXT NOT NULL CHECK (source IN ('manual', 'file', 'sync')),
  platform VARCHAR(32),
  product_type TEXT,
  symbol VARCHAR(64),
  trade_type VARCHAR(20),
  category VARCHAR(64),
  quantity NUMERIC,
  quantity_unit TEXT,
  price NUMERIC,
  exit_price NUMERIC,
  pnl NUMERIC NOT NULL DEFAULT 0,
  gross_pnl NUMERIC,
  net_pnl NUMERIC,
  final_pnl NUMERIC,
  pnl_currency TEXT,
  pnl_source TEXT,
  strategy VARCHAR(120),
  notes TEXT,
  screenshots TEXT,
  attachments JSONB NOT NULL DEFAULT '[]'::jsonb,
  custom_fields JSONB NOT NULL DEFAULT '{}'::jsonb,
  product_details JSONB NOT NULL DEFAULT '{}'::jsonb,
  charges JSONB NOT NULL DEFAULT '{}'::jsonb,
  calculation_snapshot JSONB NOT NULL DEFAULT '{}'::jsonb,
  timestamp TIMESTAMPTZ,
  entry_time TIMESTAMPTZ,
  exit_time TIMESTAMPTZ,
  open_timestamp BIGINT,
  close_timestamp BIGINT,
  unique_id VARCHAR(120),
  ticket BIGINT,
  percent_change NUMERIC,
  symbol_path TEXT,
  symbol_description TEXT,
  is_breakeven BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

INSERT INTO trading.trades (
  legacy_id, user_id, source, exchange_id, product_type, symbol, trade_type, category,
  quantity, quantity_unit, price, exit_price, pnl, gross_pnl, net_pnl, final_pnl,
  pnl_currency, pnl_source, strategy, notes, screenshots, attachments, custom_fields,
  product_details, charges, calculation_snapshot, timestamp, entry_time, exit_time,
  open_timestamp, close_timestamp, unique_id, is_breakeven, created_at, updated_at
)
SELECT id, user_id, 'manual', exchange_id, product_type, symbol, trade_type, category,
  quantity, quantity_unit, price, exit_price, pnl, gross_pnl, net_pnl, final_pnl,
  pnl_currency, pnl_source, strategy, notes, screenshots, attachments, custom_fields,
  product_details, charges, calculation_snapshot, timestamp, entry_time, exit_time,
  open_timestamp, close_timestamp, unique_id, is_breakeven, created_at, updated_at
FROM trading.manual_trades
WHERE user_id IS NOT NULL
ON CONFLICT DO NOTHING;

INSERT INTO trading.trades (
  legacy_id, user_id, account_id, source, platform, symbol, trade_type, category,
  quantity, price, exit_price, pnl, strategy, notes, screenshots, timestamp,
  open_timestamp, close_timestamp, unique_id, ticket, percent_change, symbol_path,
  symbol_description, is_breakeven, created_at, updated_at
)
SELECT id, user_id, account_id, 'sync', platform, symbol, trade_type, category,
  quantity, price, exit_price, pnl, strategy, notes, screenshots, timestamp,
  open_timestamp, close_timestamp, unique_id, ticket, percent_change, symbol_path,
  symbol_description, is_breakeven, created_at, created_at
FROM trading.api_trades
ON CONFLICT DO NOTHING;

CREATE INDEX IF NOT EXISTS trades_user_timestamp_idx ON trading.trades(user_id, timestamp DESC);
CREATE INDEX IF NOT EXISTS trades_user_source_idx ON trading.trades(user_id, source);
CREATE UNIQUE INDEX IF NOT EXISTS trades_user_unique_id_unique ON trading.trades(user_id, unique_id) WHERE unique_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS trades_sync_ticket_unique ON trading.trades(ticket);

DROP TABLE trading.manual_trades;
DROP TABLE trading.api_trades;
