INSERT INTO trading.trade_model_migration_reports (
  migration_key, total_trades, option_trades_detected, option_details_backfilled,
  rows_missing_strike, rows_missing_expiry, rows_with_unknown_side,
  rows_with_conflicting_pnl, rows_with_invalid_timestamps
)
SELECT
  '20260823_multi_asset_trade_model',
  COUNT(*),
  COUNT(*) FILTER (WHERE LOWER(COALESCE(product_type, '')) IN ('option', 'options')),
  (SELECT COUNT(*) FROM trading.option_trade_details details WHERE details.metadata ->> 'migrationSource' = 'product_details'),
  COUNT(*) FILTER (
    WHERE LOWER(COALESCE(product_type, '')) IN ('option', 'options')
      AND NOT (COALESCE(product_details ->> 'strikePrice', product_details ->> 'strike_price', '') ~ '^\s*[0-9]+(?:\.[0-9]+)?\s*$')
  ),
  COUNT(*) FILTER (
    WHERE LOWER(COALESCE(product_type, '')) IN ('option', 'options')
      AND NOT (
        COALESCE(product_details ->> 'expiryDate', product_details ->> 'expiry_date', '') ~ '^\d{4}-\d{2}-\d{2}$'
        AND TO_CHAR(TO_DATE(COALESCE(product_details ->> 'expiryDate', product_details ->> 'expiry_date'), 'YYYY-MM-DD'), 'YYYY-MM-DD')
          = COALESCE(product_details ->> 'expiryDate', product_details ->> 'expiry_date')
      )
  ),
  COUNT(*) FILTER (WHERE side IS NULL),
  COUNT(*) FILTER (WHERE
    (net_pnl IS NOT NULL AND final_pnl IS NOT NULL AND net_pnl <> final_pnl)
    OR (net_pnl IS NOT NULL AND pnl IS NOT NULL AND net_pnl <> pnl)
    OR (final_pnl IS NOT NULL AND pnl IS NOT NULL AND final_pnl <> pnl)
  ),
  COUNT(*) FILTER (WHERE
    (exit_timestamp IS NOT NULL AND exit_timestamp < entry_timestamp)
    OR (
      LOWER(COALESCE(product_type, '')) IN ('option', 'options')
      AND COALESCE(product_details ->> 'expiryDate', product_details ->> 'expiry_date', '') ~ '^\d{4}-\d{2}-\d{2}$'
      AND entry_timestamp::date > TO_DATE(COALESCE(product_details ->> 'expiryDate', product_details ->> 'expiry_date'), 'YYYY-MM-DD')
    )
  )
FROM trading.trades
ON CONFLICT (migration_key) DO UPDATE SET
  total_trades = EXCLUDED.total_trades,
  option_trades_detected = EXCLUDED.option_trades_detected,
  option_details_backfilled = EXCLUDED.option_details_backfilled,
  rows_missing_strike = EXCLUDED.rows_missing_strike,
  rows_missing_expiry = EXCLUDED.rows_missing_expiry,
  rows_with_unknown_side = EXCLUDED.rows_with_unknown_side,
  rows_with_conflicting_pnl = EXCLUDED.rows_with_conflicting_pnl,
  rows_with_invalid_timestamps = EXCLUDED.rows_with_invalid_timestamps,
  created_at = NOW();

