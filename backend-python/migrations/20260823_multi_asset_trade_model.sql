  migration_key TEXT PRIMARY KEY,
  total_trades BIGINT NOT NULL,
  option_trades_detected BIGINT NOT NULL,
  option_details_backfilled BIGINT NOT NULL,
  rows_missing_strike BIGINT NOT NULL,
  rows_missing_expiry BIGINT NOT NULL,
  rows_with_unknown_side BIGINT NOT NULL,
  rows_with_conflicting_pnl BIGINT NOT NULL,
  rows_with_invalid_timestamps BIGINT NOT NULL,
