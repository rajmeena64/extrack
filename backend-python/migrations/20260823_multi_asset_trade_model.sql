ALTER TABLE trading.trades
  ALTER COLUMN exit_timestamp DROP NOT NULL;

ALTER TABLE trading.trades
  ADD COLUMN IF NOT EXISTS entry_price NUMERIC,
  ADD COLUMN IF NOT EXISTS side TEXT,
  ADD COLUMN IF NOT EXISTS position_direction TEXT,
  ADD COLUMN IF NOT EXISTS status TEXT NOT NULL DEFAULT 'unknown',
  ADD COLUMN IF NOT EXISTS close_reason TEXT,
  ADD COLUMN IF NOT EXISTS total_charges NUMERIC;

UPDATE trading.trades
SET entry_price = price
WHERE entry_price IS NULL AND price IS NOT NULL;

UPDATE trading.trades
SET side = LOWER(BTRIM(trade_type))
WHERE side IS NULL AND LOWER(BTRIM(trade_type)) IN ('buy', 'sell');

UPDATE trading.trades
SET position_direction = CASE side WHEN 'buy' THEN 'long' WHEN 'sell' THEN 'short' END
WHERE position_direction IS NULL
  AND side IN ('buy', 'sell')
  AND LOWER(COALESCE(product_type, '')) IN ('forex', 'cfd', 'future', 'futures', 'perpetual', 'option', 'options');

UPDATE trading.trades
SET status = CASE LOWER(COALESCE(
      NULLIF(custom_fields ->> 'status', ''),
      NULLIF(product_details ->> 'status', ''),
      NULLIF(product_details ->> 'tradeStatus', '')
    ))
      WHEN 'open' THEN 'open'
      WHEN 'partially_closed' THEN 'partially_closed'
      WHEN 'partially closed' THEN 'partially_closed'
      WHEN 'closed' THEN 'closed'
      WHEN 'expired' THEN 'expired'
      WHEN 'exercised' THEN 'exercised'
      WHEN 'assigned' THEN 'assigned'
      WHEN 'liquidated' THEN 'liquidated'
      WHEN 'cancelled' THEN 'cancelled'
      ELSE status
    END
WHERE status = 'unknown';

UPDATE trading.trades
SET status = 'expired',
    close_reason = COALESCE(close_reason, CASE
      WHEN LOWER(COALESCE(product_details ->> 'expirationOutcome', product_details ->> 'expiration_outcome', '')) = 'expired_worthless'
        THEN 'expired_worthless'
      ELSE 'unknown'
    END)
WHERE status = 'unknown'
  AND LOWER(COALESCE(product_type, '')) IN ('option', 'options')
  AND (
    LOWER(COALESCE(product_details ->> 'closeType', product_details ->> 'close_type', '')) = 'expired'
    OR LOWER(COALESCE(product_details ->> 'expirationOutcome', product_details ->> 'expiration_outcome', '')) = 'expired_worthless'
  );

UPDATE trading.trades
SET status = 'closed'
WHERE status = 'unknown'
  AND exit_timestamp IS NOT NULL
  AND exit_timestamp >= entry_timestamp;

UPDATE trading.trades
SET status = 'open'
WHERE status = 'unknown'
  AND exit_timestamp IS NULL;

UPDATE trading.trades
SET total_charges = gross_pnl - net_pnl
WHERE total_charges IS NULL
  AND gross_pnl IS NOT NULL
  AND net_pnl IS NOT NULL
  AND gross_pnl >= net_pnl;

