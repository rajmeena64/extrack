WITH option_candidates AS (
  SELECT
    trade.id AS trade_id,
    NULLIF(BTRIM(COALESCE(trade.product_details ->> 'underlyingSymbol', trade.product_details ->> 'underlying_symbol')), '') AS underlying_symbol,
    CASE LOWER(COALESCE(trade.product_details ->> 'optionType', trade.product_details ->> 'option_type', ''))
      WHEN 'call' THEN 'call' WHEN 'ce' THEN 'call' WHEN 'put' THEN 'put' WHEN 'pe' THEN 'put'
    END AS option_type,
    COALESCE(trade.product_details ->> 'strikePrice', trade.product_details ->> 'strike_price') AS strike_text,
    COALESCE(trade.product_details ->> 'expiryDate', trade.product_details ->> 'expiry_date') AS expiry_text,
    COALESCE(trade.product_details ->> 'contractMultiplier', trade.product_details ->> 'contract_multiplier') AS multiplier_text,
    COALESCE(trade.product_details ->> 'lotSize', trade.product_details ->> 'lot_size') AS lot_size_text,
    COALESCE(trade.product_details ->> 'settlementPrice', trade.product_details ->> 'settlement_price') AS settlement_price_text,
    NULLIF(BTRIM(COALESCE(trade.product_details ->> 'expirationOutcome', trade.product_details ->> 'expiration_outcome')), '') AS expiration_outcome
  FROM trading.trades trade
  WHERE LOWER(COALESCE(trade.product_type, '')) IN ('option', 'options')
), reliable AS (
  SELECT * FROM option_candidates
  WHERE underlying_symbol IS NOT NULL
    AND option_type IS NOT NULL
    AND CASE WHEN strike_text ~ '^\s*[0-9]+(?:\.[0-9]+)?\s*$' THEN strike_text::numeric > 0 ELSE FALSE END
    AND expiry_text ~ '^\d{4}-\d{2}-\d{2}$'
    AND TO_CHAR(TO_DATE(expiry_text, 'YYYY-MM-DD'), 'YYYY-MM-DD') = expiry_text
)
INSERT INTO trading.option_trade_details (
  trade_id, underlying_symbol, option_type, strike_price, expiry_date,
  contract_multiplier, lot_size, settlement_price, expiration_outcome, metadata
)
SELECT
  trade_id, underlying_symbol, option_type, strike_text::numeric, expiry_text::date,
  CASE WHEN multiplier_text ~ '^\s*[0-9]+(?:\.[0-9]+)?\s*$'
    THEN CASE WHEN multiplier_text::numeric > 0 THEN multiplier_text::numeric ELSE 1 END ELSE 1 END,
  CASE WHEN lot_size_text ~ '^\s*[0-9]+(?:\.[0-9]+)?\s*$'
    THEN CASE WHEN lot_size_text::numeric > 0 THEN lot_size_text::numeric END END,
  CASE WHEN settlement_price_text ~ '^\s*-?[0-9]+(?:\.[0-9]+)?\s*$' THEN settlement_price_text::numeric END,
  expiration_outcome,
  JSONB_BUILD_OBJECT('migrationSource', 'product_details')
FROM reliable
ON CONFLICT (trade_id) DO NOTHING;

