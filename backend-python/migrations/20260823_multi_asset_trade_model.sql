  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT trade_executions_action_check CHECK (action IN ('buy', 'sell')),
  CONSTRAINT trade_executions_position_effect_check CHECK (position_effect IN ('open', 'close', 'unknown')),
  CONSTRAINT trade_executions_quantity_check CHECK (quantity > 0)
);

